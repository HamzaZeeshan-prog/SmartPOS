import { jsPDF } from 'jspdf';
import { Sale, Shop } from '../types/pos';

export function buildReceiptPdfDoc(
  sale: Sale,
  shop: Shop,
  rollWidth: '58mm' | '80mm' = shop.thermalPrinterWidth || '80mm'
): { doc: jsPDF; fileName: string } {
  const widthMm = rollWidth === '58mm' ? 58 : 80;
  const lineCount = sale.items.length;
  const heightMm = Math.max(135, 92 + lineCount * 11 + (sale.discountTotal > 0 ? 6 : 0) + (sale.taxTotal > 0 ? 6 : 0));

  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: [widthMm, heightMm],
  });

  const margin = 4;
  const contentWidth = widthMm - margin * 2;
  let y = 8;

  // Store Header
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(rollWidth === '58mm' ? 10 : 12);
  doc.text(shop.name.toUpperCase(), widthMm / 2, y, { align: 'center', maxWidth: contentWidth });
  y += 4.5;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(rollWidth === '58mm' ? 6.5 : 7.5);
  doc.text(`${shop.address}, ${shop.city}`, widthMm / 2, y, { align: 'center', maxWidth: contentWidth });
  y += 3.5;
  doc.text(`Tel: ${shop.phone}`, widthMm / 2, y, { align: 'center' });
  y += 4;

  // Dashed divider
  doc.setLineWidth(0.2);
  doc.line(margin, y, widthMm - margin, y);
  y += 4;

  // Meta rows
  const formattedDate = new Date(sale.createdAt).toLocaleString('en-PK', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  });

  const drawMeta = (label: string, val: string) => {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(rollWidth === '58mm' ? 6.5 : 7.5);
    doc.text(label, margin, y);
    doc.setFont('helvetica', 'bold');
    doc.text(val, widthMm - margin, y, { align: 'right' });
    y += 3.8;
  };

  drawMeta('Invoice:', sale.invoiceNumber);
  drawMeta('Date:', formattedDate);
  drawMeta('Cashier:', sale.cashierName);
  if (sale.customerName) {
    drawMeta('Customer:', sale.customerName);
  }

  doc.line(margin, y, widthMm - margin, y);
  y += 4;

  // Table Header
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(rollWidth === '58mm' ? 6.5 : 7.5);
  doc.text('ITEM', margin, y);
  doc.text('QTY', widthMm - 22, y, { align: 'right' });
  doc.text('AMT', widthMm - margin, y, { align: 'right' });
  y += 2;
  doc.line(margin, y, widthMm - margin, y);
  y += 4;

  // Line items
  for (const item of sale.items) {
    const lineTotal = item.unitPrice * item.quantity - item.itemDiscount;
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(rollWidth === '58mm' ? 7 : 8);
    const wrappedName = doc.splitTextToSize(item.product.name, contentWidth - 24);
    doc.text(wrappedName, margin, y);
    doc.text(String(item.quantity), widthMm - 22, y, { align: 'right' });
    doc.text(lineTotal.toLocaleString(), widthMm - margin, y, { align: 'right' });
    y += wrappedName.length * 3.4;

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(rollWidth === '58mm' ? 6 : 6.8);
    doc.text(`${shop.currency} ${item.unitPrice.toLocaleString()} x ${item.quantity}`, margin, y);
    y += 3.8;
  }

  doc.line(margin, y, widthMm - margin, y);
  y += 4;

  // Totals
  drawMeta('Subtotal', `${shop.currency} ${sale.subtotal.toLocaleString()}`);
  if (sale.discountTotal > 0) {
    drawMeta('Discount', `- ${shop.currency} ${sale.discountTotal.toLocaleString()}`);
  }
  if (sale.deliveryCharge > 0) {
    drawMeta('Delivery', `${shop.currency} ${sale.deliveryCharge.toLocaleString()}`);
  }
  if (sale.taxTotal > 0) {
    drawMeta('GST / Tax', `${shop.currency} ${sale.taxTotal.toLocaleString()}`);
  }

  y += 1;
  doc.setDrawColor(40, 40, 40);
  doc.rect(margin, y - 3, contentWidth, 7);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(rollWidth === '58mm' ? 8.5 : 10);
  doc.text('NET TOTAL', margin + 1.5, y + 1.8);
  doc.text(`${shop.currency} ${sale.grandTotal.toLocaleString()}`, widthMm - margin - 1.5, y + 1.8, {
    align: 'right',
  });
  y += 8;

  const paymentMethod = sale.payments.map((p) => p.method.toUpperCase()).join(', ');
  const totalPaid = sale.payments.reduce((s, p) => s + p.amount, 0);
  const change = sale.payments.reduce((s, p) => s + (p.changeReturned || 0), 0);

  drawMeta('Payment Mode', paymentMethod);
  drawMeta('Amount Paid', `${shop.currency} ${totalPaid.toLocaleString()}`);
  if (change > 0) {
    drawMeta('Change Returned', `${shop.currency} ${change.toLocaleString()}`);
  }

  y += 2;
  doc.line(margin, y, widthMm - margin, y);
  y += 4.5;
  doc.setFont('helvetica', 'italic');
  doc.setFontSize(rollWidth === '58mm' ? 6.5 : 7.5);
  doc.text(shop.receiptMessage, widthMm / 2, y, { align: 'center', maxWidth: contentWidth });
  y += 4;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(6);
  doc.text(`Generated by ${shop.name}`, widthMm / 2, y, { align: 'center' });

  const safeInv = sale.invoiceNumber.replace(/[^a-zA-Z0-9_-]/g, '_');
  return { doc, fileName: `Receipt_${safeInv}.pdf` };
}

export async function shareReceiptAsPdf(
  sale: Sale,
  shop: Shop,
  rollWidth: '58mm' | '80mm' = shop.thermalPrinterWidth || '80mm'
): Promise<'shared' | 'downloaded'> {
  const { doc, fileName } = buildReceiptPdfDoc(sale, shop, rollWidth);
  const blob = doc.output('blob');
  const file = new File([blob], fileName, { type: 'application/pdf' });

  const nav = navigator as Navigator & {
    canShare?: (data: ShareData) => boolean;
  };

  if (typeof nav.share === 'function' && (!nav.canShare || nav.canShare({ files: [file] }))) {
    try {
      await nav.share({
        title: `${shop.name} Receipt ${sale.invoiceNumber}`,
        text: `Receipt ${sale.invoiceNumber} from ${shop.name} — Total: ${shop.currency} ${sale.grandTotal.toLocaleString()}`,
        files: [file],
      });
      return 'shared';
    } catch {
      // Fallback to direct PDF download if Web Share API is blocked in embedded preview
    }
  }

  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = fileName;
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
  setTimeout(() => URL.revokeObjectURL(url), 1500);
  return 'downloaded';
}
